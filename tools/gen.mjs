// Generates schemas/*.gschema.xml and the SETTERS block in extension.js from settings-spec.js.
// Re-run whenever settings-spec.js changes:
//     node tools/gen.mjs && glib-compile-schemas schemas/
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const {SCHEMA_ID, SPEC} = await import(pathToFileURL(path.join(root, 'settings-spec.js')).href);

const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const num = v => (Number.isInteger(v) ? String(v) : String(v));

// ── schema XML ──
const keys = [];
for (const g of SPEC) {
    for (const r of g.rows) {
        const t = r.type === 'bool' ? 'b' : r.type === 'int' ? 'i' : r.type === 'string' ? 's' : 'd';
        const range = (r.type === 'bool' || r.type === 'string') ? '' : `\n      <range min="${num(r.min)}" max="${num(r.max)}"/>`;
        const def = r.type === 'string' ? `'${esc(r.def)}'` : r.type === 'bool' ? String(r.def) : num(r.type === 'double' && Number.isInteger(r.def) ? r.def.toFixed(1) : r.def);
        keys.push(`    <key name="${r.key}" type="${t}">
      <default>${def}</default>${range}
      <summary>${esc(r.title)}</summary>
      <description>${esc(r.sub)}</description>
    </key>`);
    }
}
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated from settings-spec.js by tools/gen.mjs. Do not edit by hand. -->
<schemalist>
  <schema id="${SCHEMA_ID}" path="/org/gnome/shell/extensions/koipond/">
${keys.join('\n')}
  </schema>
</schemalist>
`;
fs.mkdirSync(path.join(root, 'schemas'), {recursive: true});
fs.writeFileSync(path.join(root, 'schemas', `${SCHEMA_ID}.gschema.xml`), xml);

// ── khối SETTERS trong extension.js ──
const lines = [];
const names = [];
for (const g of SPEC) {
    for (const r of g.rows) {
        if (r.name) {
            lines.push(`    '${r.key}': v => { ${r.name} = v; },`);
            names.push(r.name);
        }
    }
}
const block = `// <<settings-setters (generated by tools/gen.mjs, do not edit by hand)
const SETTERS = {
${lines.join('\n')}
};
// settings-setters>>`;

const extPath = path.join(root, 'extension.js');
let src = fs.readFileSync(extPath, 'utf8');
const re = /\/\/ <<settings-setters[\s\S]*?\/\/ settings-setters>>/;
if (!re.test(src)) {
    console.error('Could not find the // <<settings-setters block in extension.js');
    process.exit(1);
}
src = src.replace(re, () => block);
fs.writeFileSync(extPath, src);

console.log(`OK: ${keys.length} keys, ${names.length} variables`);
